"""Manifest generation.

Produces a JSON file for tooling and a ready-to-drop Luau module for Roblox.
The Luau module lists every rendered file with its loop metadata and a zeroed
``assetId`` that you fill in after uploading the WAVs.
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from . import layout
from .config import Preset


def preset_entry(
    preset: Preset,
    layers: list[dict[str, Any]],
    events: list[dict[str, Any]],
    sample_rate: int,
    filename_prefix: str,
) -> dict[str, Any]:
    return {
        "name": preset.name,
        "slug": preset.slug,
        "engine": layout.describe(preset.block),
        "displacementLitres": round(layout.displacement_litres(preset.block), 3),
        "cylinders": preset.block.cylinders,
        "layout": preset.block.layout,
        "ignition": preset.block.ignition,
        "strokes": preset.block.strokes,
        "compression": preset.block.compression,
        "octane": preset.block.octane,
        "idleRpm": preset.engine.idle_rpm,
        "redlineRpm": preset.engine.redline_rpm,
        "turbo": bool(preset.turbo.enabled),
        "turboKind": preset.turbo.kind if preset.turbo.enabled else None,
        "sampleRate": sample_rate,
        "filenamePrefix": filename_prefix,
        "layers": layers,
        "events": events,
    }


def _unique_by_slug(entries: list[dict[str, Any]]) -> dict[str, Any]:
    """Index entries by slug, disambiguating collisions instead of dropping one."""
    out: dict[str, Any] = {}
    for e in entries:
        slug = e["slug"]
        if slug in out:
            n = 2
            while f"{slug}_{n}" in out:
                n += 1
            slug = f"{slug}_{n}"
            e = {**e, "slug": slug}
        out[slug] = e
    return out


def write_manifest(
    entries: list[dict[str, Any]],
    out_dir: str | Path,
    sample_rate: int,
    bit_depth: int,
) -> tuple[Path, Path]:
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    doc = {
        "generator": "tools/soundgen",
        "generated": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "sampleRate": sample_rate,
        "bitDepth": bit_depth,
        "presets": _unique_by_slug(entries),
    }
    json_path = out_dir / "manifest.json"
    json_path.write_text(json.dumps(doc, indent=2, ensure_ascii=False), encoding="utf-8")

    luau_path = out_dir / "EngineSoundManifest.luau"
    luau_path.write_text(_to_luau(doc), encoding="utf-8")
    return json_path, luau_path


def _num(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, float):
        return f"{v:.4f}".rstrip("0").rstrip(".") or "0"
    return str(v)


def _table(d: dict[str, Any], indent: int = 0, quote_keys: bool = True) -> str:
    pad = "\t" * indent
    inner = "\t" * (indent + 1)
    lines = ["{"]
    for k, v in d.items():
        key = f'["{k}"]' if quote_keys else k
        lines.append(f"{inner}{key} = {_value(v, indent + 1, quote_keys)},")
    lines.append(pad + "}")
    return "\n".join(lines)


def _value(v: Any, indent: int, quote_keys: bool = True) -> str:
    if isinstance(v, dict):
        return _table(v, indent, quote_keys)
    if isinstance(v, (list, tuple)):
        if not v:
            return "{}"
        items = ", ".join(_value(x, indent, quote_keys) for x in v)
        return "{" + items + "}"
    if isinstance(v, str):
        return json.dumps(v, ensure_ascii=False)
    if v is None:
        return "nil"
    return _num(v)


def _to_luau(doc: dict[str, Any]) -> str:
    header = (
        "-- AUTO-GENERATED by tools/soundgen -- do not edit by hand.\n"
        f"-- Generated: {doc['generated']}\n"
        f"-- Sample rate: {doc['sampleRate']} Hz, bit depth: {doc['bitDepth']}\n"
        "--\n"
        "-- After uploading the rendered WAV files, set each `assetId` to the\n"
        "-- uploaded rbxassetid (numbers only). Loop bounds are in seconds: feed\n"
        "-- `loopStart`/`loopEnd` straight into AudioPlayer.LoopRegion.\n\n"
        "local Manifest = "
    )
    body = _table(
        {
            "generated": doc["generated"],
            "sampleRate": doc["sampleRate"],
            "bitDepth": doc["bitDepth"],
            "presets": doc["presets"],
        },
        0,
        quote_keys=False,
    )
    return header + body + "\n\nreturn Manifest\n"
