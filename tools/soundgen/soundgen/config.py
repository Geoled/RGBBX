_NESTED = {
    "engine": Engine,
    "block": Block,
    "exhaust": Exhaust,
    "intake": Intake,
    "turbo": Turbo,
    "turbine": Turbine,
    "mechanical": Mechanical,
    "space": Space,
    "character": Character,
    "render": RenderCfg,
}

# Keys allowed directly at the top level of a preset file.
_TOP_LEVEL = {"name", "seed", "notes", *_NESTED}

_ALLOWED_LAYOUTS = {"inline", "v", "boxer", "rotary", "radial", "turbine"}
_ALLOWED_IGNITIONS = {"spark", "compression", "turbine"}
_ALLOWED_TURBO_KINDS = {"turbo", "supercharger"}


def _number(value: Any, name: str) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise ValueError(f"{name} must be a number")
    number = float(value)
    if not math.isfinite(number):
        raise ValueError(f"{name} must be finite")
    return number


def _range(value: Any, name: str, lo: float, hi: float) -> float:
    number = _number(value, name)
    if not (lo <= number <= hi):
        raise ValueError(f"{name} must be between {lo:g} and {hi:g}")
    return number


def _positive(value: Any, name: str) -> float:
    number = _number(value, name)
    if number <= 0.0:
        raise ValueError(f"{name} must be > 0")
    return number


def _modes(modes: list[list[float]], where: str) -> None:
    for index, mode in enumerate(modes):
        if len(mode) != 3:
            raise ValueError(f"{where}.modes[{index}] must be [frequency_hz, q, gain]")
        hz, q, gain = (_number(v, f"{where}.modes[{index}]") for v in mode)
        if hz <= 0.0 or q <= 0.0 or gain < 0.0:
            raise ValueError(
                f"{where}.modes[{index}] needs frequency_hz > 0, q > 0 and gain >= 0"
            )


def _suggest(key: str, candidates) -> str:
    import difflib

    close = difflib.get_close_matches(key, sorted(candidates), n=1, cutoff=0.55)
    return f" (did you mean '{close[0]}'?)" if close else ""


def _coerce(cls, key: str, value: Any, where: str) -> Any:
    """Check a value against its dataclass annotation and convert it.

    TOML is typed, but hand-edited presets and programmatic callers are not:
    ``enabled = "false"`` used to load and then be *truthy*, and a string in a
    numeric field survived until something far away did arithmetic on it. Doing
    the check here keeps the failure next to the offending line.
    """
    hints = getattr(cls, "__annotations__", {})
    hint = hints.get(key)
    if hint in (None, Any):
        return value
    text = str(hint)
    if text.startswith("bool"):
        if not isinstance(value, bool):
            raise TypeError(f"{where}.{key} must be true or false, got {value!r}")
        return value
    if text.startswith(("float", "int")):
        if isinstance(value, bool) or not isinstance(value, (int, float)):
            raise TypeError(f"{where}.{key} must be a number, got {value!r}")
        return int(value) if text.startswith("int") else float(value)
    if text.startswith("str"):
        if not isinstance(value, str):
            raise TypeError(f"{where}.{key} must be a string, got {value!r}")
        return value
    if text.startswith("list"):
        if not isinstance(value, (list, tuple)):
            raise TypeError(f"{where}.{key} must be a list, got {value!r}")
        if "list[" in text[5:]:
            # Nested lists (the resonator banks: [[hz, q, gain], ...]) are
            # shape-checked by _modes, which gives a better error than this.
            return [list(item) if isinstance(item, (list, tuple)) else item for item in value]
        if "float" in text:
            out = []
            for item in value:
                if isinstance(item, bool) or not isinstance(item, (int, float)):
                    raise TypeError(f"{where}.{key} must be a list of numbers, got {item!r}")
                out.append(float(item))
            return out
        return list(value)
    return value


def _fill(cls, data: dict[str, Any] | None, where: str = ""):
    obj = cls()
    if not data:
        return obj
    known = {f.name for f in fields(cls)}
    for key, value in data.items():
        if key in known:
            setattr(obj, key, _coerce(cls, key, value, where or cls.__name__.lower()))
        else:
            section = f"[{where}] " if where else ""
            raise KeyError(
                f"{section}unknown option '{key}'{_suggest(key, known)}"
            )
    return obj


def preset_from_dict(raw: dict[str, Any], name: str = "Untitled") -> Preset:
    unknown = [k for k in raw if k not in _TOP_LEVEL]
    if unknown:
        key = unknown[0]
        raise KeyError(
            f"unknown section or key '{key}'{_suggest(key, _TOP_LEVEL)}"
        )
    p = Preset()
    p.name = str(raw.get("name", name))
    p.seed = int(raw.get("seed", 0))
    p.notes = str(raw.get("notes", ""))
    for key, cls in _NESTED.items():
        setattr(p, key, _fill(cls, raw.get(key), key))
    p.validate()
    return p


def discover_presets(directory: str | Path) -> list[Path]:
    """Usable preset files in ``directory``, sorted.

    Names starting with ``_`` or ``.`` are templates and notes, not engines, so
    they are deliberately skipped. That makes it safe to keep
    ``presets/_template.toml`` next to the real roster.
    """
    return sorted(
        p for p in Path(directory).glob("*.toml") if not p.name.startswith(("_", "."))
    )


def load_preset(path: str | Path) -> Preset:
    path = Path(path)
    with open(path, "rb") as fh:
        try:
            raw = tomllib.load(fh)
        except tomllib.TOMLDecodeError as exc:
            raise ValueError(f"{path.name}: invalid TOML: {exc}") from exc
    try:
        return preset_from_dict(raw, name=path.stem)
    except (KeyError, ValueError, TypeError) as exc:
        message = exc.args[0] if exc.args else str(exc)
        raise ValueError(f"{path.name}: {message}") from exc


def save_preset(preset: Preset, path: str | Path) -> Path:
    """Write a preset back out as TOML (useful for round-tripping)."""
    path = Path(path)
    data = asdict(preset)
    lines: list[str] = []

    def emit(value, prefix: str = "") -> None:
        scalars = {k: v for k, v in value.items() if not isinstance(v, dict)}
        tables = {k: v for k, v in value.items() if isinstance(v, dict)}
        for k, v in scalars.items():
            # TOML has no null. A field left as None is written by omitting it,
            # so it comes back as its dataclass default on the next load --
            # which is exactly what None meant in the first place.
            if v is None:
                continue
            lines.append(f"{k} = {_toml(v)}")
        for k, v in tables.items():
            lines.append("")
            lines.append(f"[{prefix}{k}]" if prefix else f"[{k}]")
            emit(v, f"{prefix}{k}." if prefix else f"{k}.")

    emit(data)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def _toml(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, str):
        return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'
    if isinstance(value, (list, tuple)):
        return "[" + ", ".join(_toml(v) for v in value if v is not None) + "]"
    raise TypeError(f"cannot serialise {type(value)!r}")


def _validate(preset: "Preset") -> None:
    b = preset.block
    if b.layout not in _ALLOWED_LAYOUTS:
        raise ValueError(f"unknown layout '{b.layout}' (expected one of {sorted(_ALLOWED_LAYOUTS)})")
    if b.ignition not in _ALLOWED_IGNITIONS:
        raise ValueError(
            f"unknown ignition '{b.ignition}' (expected one of {sorted(_ALLOWED_IGNITIONS)})"
        )
    if b.layout == "turbine" and b.ignition != "turbine":
        raise ValueError("a turbine layout needs ignition = 'turbine'")
    if b.ignition == "turbine" and b.layout != "turbine":
        raise ValueError("ignition = 'turbine' is only valid with layout = 'turbine'")
    if b.cylinders < 1:
        raise ValueError("cylinders must be >= 1")
    if b.cylinders > 16:
        raise ValueError("cylinders must be <= 16")
    if b.strokes not in (2, 4):
        raise ValueError("strokes must be 2 or 4")
    if b.firing_offsets:
        # An uneven firing order is a list of phase offsets, one per cylinder.
        # A short list used to be padded with zeros, which silently put several
        # cylinders at the same phase; a long one used to be truncated.
        if len(b.firing_offsets) != int(b.cylinders):
            raise ValueError(
                f"firing_offsets has {len(b.firing_offsets)} entries for "
                f"{int(b.cylinders)} cylinders; give one per cylinder or leave it empty"
            )
        for index, value in enumerate(b.firing_offsets):
            if not math.isfinite(float(value)):
                raise ValueError(f"firing_offsets[{index}] must be finite")
            if not (0.0 <= float(value) < 1.0):
                raise ValueError(f"firing_offsets[{index}] must be in [0, 1)")
    if b.bore_mm <= 0 or b.stroke_mm <= 0:
        raise ValueError("bore and stroke must be positive")
    if not (4.0 <= b.compression <= 30.0):
        raise ValueError("compression must be between 4 and 30")
    if not (70.0 <= b.octane <= 120.0):
        raise ValueError("octane must be between 70 and 120")
    if not (1.0 <= b.rod_ratio <= 3.0):
        raise ValueError("rod_ratio must be between 1.0 and 3.0")
    # 0 means "auto" for all three VE knobs, so only a non-zero value is checked
    if b.ve_peak_rpm_frac and not (0.05 <= b.ve_peak_rpm_frac <= 0.95):
        raise ValueError("ve_peak_rpm_frac must be 0 (auto) or between 0.05 and 0.95")
    if b.ve_droop and not (0.0 < b.ve_droop <= 0.9):
        raise ValueError("ve_droop must be 0 (auto) or between 0 and 0.9")
    if b.ve_peak_value and not (0.3 <= b.ve_peak_value <= 1.6):
        raise ValueError("ve_peak_value must be 0 (auto) or between 0.3 and 1.6")
    if not (preset.engine.idle_rpm > 0 and preset.engine.redline_rpm > preset.engine.idle_rpm):
        raise ValueError("need 0 < idle_rpm < redline_rpm")
    _positive(preset.engine.starter_rpm, "engine.starter_rpm")
    if preset.engine.starter_rpm >= preset.engine.redline_rpm:
        raise ValueError("engine.starter_rpm must be below engine.redline_rpm")
    if preset.render.sample_rate < 8000:
        raise ValueError("sample_rate looks too low")
    if preset.render.block_size < 64:
        raise ValueError("block_size must be >= 64")
    m = preset.mechanical
    for key in (
        "valvetrain_gain", "injector_gain", "accessory_gain", "hiss_gain",
        "crank_gain", "slap_gain", "chain_gain", "friction_gain",
    ):
        if getattr(m, key) < 0.0:
            raise ValueError(f"mechanical.{key} must be >= 0")
    if m.crank_hz <= 0.0 or m.slap_hz <= 0.0 or m.chain_hz <= 0.0:
        raise ValueError("mechanical resonances must be > 0 Hz")
    if not (2 <= int(m.valves_per_cyl) <= 8):
        raise ValueError("mechanical.valves_per_cyl must be between 2 and 8")
    if not (0.0 <= m.valve_open_gain <= 2.0):
        raise ValueError("mechanical.valve_open_gain must be between 0 and 2")
    if m.mech_scatter_ms < 0.0:
        raise ValueError("mechanical.mech_scatter_ms must be >= 0")
    if not (0.0 <= preset.space.mix <= 0.95):
        # the voice clamps the wet mix at 0.95, so a value above it would be
        # accepted here and then quietly ignored
        raise ValueError("space.mix must be between 0 and 0.95")
    if preset.space.decay_s <= 0.0:
        raise ValueError("space.decay_s must be > 0")
    if preset.space.damping_hz <= 0.0:
        raise ValueError("space.damping_hz must be > 0")
    if preset.turbo.max_boost_bar < 0.0:
        raise ValueError("turbo.max_boost_bar must be >= 0")
    if preset.turbo.spool_span_rpm <= 0.0:
        raise ValueError("turbo.spool_span_rpm must be > 0")
    it = preset.intake
    if it.noise_gain < 0.0 or it.pulse_gain < 0.0:
        raise ValueError("intake.noise_gain and intake.pulse_gain must be >= 0")
    if it.band_hi_hz <= it.band_lo_hz:
        raise ValueError("intake.band_hi_hz must be above intake.band_lo_hz")
    if it.noise_tilt_hz <= 0.0:
        raise ValueError("intake.noise_tilt_hz must be > 0")
    if not (-24.0 <= it.noise_tilt_db_oct <= 6.0):
        raise ValueError("intake.noise_tilt_db_oct must be between -24 and 6")

    # --- exhaust ---------------------------------------------------------- #
    ex = preset.exhaust
    _positive(ex.pipe_length_m, "exhaust.pipe_length_m")
    _range(ex.pipe_temp_c, "exhaust.pipe_temp_c", -50.0, 1500.0)
    _range(ex.comb_gain, "exhaust.comb_gain", 0.0, 10.0)
    if not (1 <= int(ex.comb_repeats) <= 32):
        raise ValueError("exhaust.comb_repeats must be between 1 and 32")
    _positive(ex.muffler_cutoff_hz, "exhaust.muffler_cutoff_hz")
    _range(ex.bank_asymmetry, "exhaust.bank_asymmetry", -1.0, 2.0)
    if ex.runner_length_m < 0.0:
        raise ValueError("exhaust.runner_length_m must be >= 0")
    _range(ex.runner_spread, "exhaust.runner_spread", 0.0, 2.0)
    _range(ex.runner_reflect, "exhaust.runner_reflect", 0.0, 1.0)
    for key in ("flow_noise", "flow_burst", "tail_noise"):
        if getattr(ex, key) < 0.0:
            raise ValueError(f"exhaust.{key} must be >= 0")
    if ex.flow_band_hi_hz <= ex.flow_band_lo_hz:
        raise ValueError("exhaust.flow_band_hi_hz must be above exhaust.flow_band_lo_hz")
    _range(ex.formant_shift, "exhaust.formant_shift", -0.5, 1.0)
    _modes(ex.modes, "exhaust")

    # --- intake ----------------------------------------------------------- #
    if it.runner_length_m < 0.0:
        raise ValueError("intake.runner_length_m must be >= 0")
    _range(it.runner_spread, "intake.runner_spread", 0.0, 2.0)
    _range(it.runner_reflect, "intake.runner_reflect", 0.0, 1.0)
    _range(it.runner_sound_speed, "intake.runner_sound_speed", 50.0, 1000.0)
    _modes(it.modes, "intake")

    # --- turbo / supercharger -------------------------------------------- #
    tb = preset.turbo
    if tb.kind not in _ALLOWED_TURBO_KINDS:
        raise ValueError(
            f"unknown turbo.kind '{tb.kind}' (expected one of {sorted(_ALLOWED_TURBO_KINDS)})"
        )
    _range(tb.max_boost_bar, "turbo.max_boost_bar", 0.0, 20.0)
    if tb.spool_rpm < 0.0:
        raise ValueError("turbo.spool_rpm must be >= 0")
    _positive(tb.whistle_hz, "turbo.whistle_hz")
    if tb.whistle_span_hz < 0.0:
        raise ValueError("turbo.whistle_span_hz must be >= 0")
    for key in ("whistle_gain", "whoosh_gain"):
        if getattr(tb, key) < 0.0:
            raise ValueError(f"turbo.{key} must be >= 0")
    _range(tb.idle_whistle, "turbo.idle_whistle", 0.0, 1.0)

    # --- gas turbine cycle ------------------------------------------------- #
    # Only meaningful for a turbine, but validated whenever present so that a
    # typo in a future turbine preset fails at load time instead of at 40 000
    # rpm in the dyno.
    gt = preset.turbine
    _range(gt.pressure_ratio, "turbine.pressure_ratio", 1.05, 40.0)
    _range(gt.idle_turbine_inlet_c, "turbine.idle_turbine_inlet_c", 100.0, 1700.0)
    _range(gt.max_turbine_inlet_c, "turbine.max_turbine_inlet_c", 200.0, 1800.0)
    if gt.max_turbine_inlet_c <= gt.idle_turbine_inlet_c:
        raise ValueError(
            "turbine.max_turbine_inlet_c must be above turbine.idle_turbine_inlet_c"
        )
    for key in (
        "compressor_efficiency",
        "turbine_efficiency",
        "combustor_efficiency",
        "mechanical_efficiency",
    ):
        _range(getattr(gt, key), f"turbine.{key}", 0.05, 1.0)
    _positive(gt.mass_flow_kg_s, "turbine.mass_flow_kg_s")
    _range(gt.pressure_loss, "turbine.pressure_loss", 0.5, 1.0)
    _positive(gt.spool_tau_s, "turbine.spool_tau_s")
    _positive(gt.wind_down_tau_s, "turbine.wind_down_tau_s")

    # --- mechanical ------------------------------------------------------- #
    _positive(m.valvetrain_bright_hz, "mechanical.valvetrain_bright_hz")
    _positive(m.accessory_hz, "mechanical.accessory_hz")
    if m.hiss_hi_hz <= m.hiss_lo_hz:
        raise ValueError("mechanical.hiss_hi_hz must be above mechanical.hiss_lo_hz")
    if m.friction_hi_hz <= m.friction_lo_hz:
        raise ValueError("mechanical.friction_hi_hz must be above mechanical.friction_lo_hz")
    _range(m.hiss_tilt_db, "mechanical.hiss_tilt_db", -36.0, 12.0)
    _range(m.mech_scatter_ms, "mechanical.mech_scatter_ms", 0.0, 10.0)

    # --- space ------------------------------------------------------------ #
    sp = preset.space
    _range(sp.predelay_ms, "space.predelay_ms", 0.0, 250.0)
    _range(sp.early_gain, "space.early_gain", 0.0, 2.0)
    _range(sp.tail_gain, "space.tail_gain", 0.0, 2.0)
    if int(sp.seed) < 0:
        raise ValueError("space.seed must be >= 0")

    # --- character -------------------------------------------------------- #
    ch = preset.character
    _range(ch.brightness_db, "character.brightness_db", -24.0, 24.0)
    _positive(ch.presence_hz, "character.presence_hz")
    _positive(ch.presence_q, "character.presence_q")
    _positive(ch.air_cutoff_hz, "character.air_cutoff_hz")
    if not (1 <= int(ch.air_order) <= 12):
        raise ValueError("character.air_order must be between 1 and 12")
    _range(ch.aggression, "character.aggression", 0.0, 6.0)
    for key in ("lumpiness", "irregularity", "idle_floor", "ccv"):
        _range(getattr(ch, key), f"character.{key}", 0.0, 1.0)
    _range(ch.combustion_gain, "character.combustion_gain", 0.0, 5.0)
    _range(ch.load_sharpening, "character.load_sharpening", 0.0, 2.0)
    _range(ch.transient_bark, "character.transient_bark", 0.0, 2.0)
    _positive(ch.pulse_ref_rpm, "character.pulse_ref_rpm")
    _range(ch.pulse_min_scale, "character.pulse_min_scale", 0.0, 1.0)

    # --- render ----------------------------------------------------------- #
    r = preset.render
    if int(r.channels) not in (1, 2):
        raise ValueError("render.channels must be 1 or 2")
    if int(r.bit_depth) not in (16, 24):
        raise ValueError("render.bit_depth must be 16 or 24")
    if not (8000 <= int(r.sample_rate) <= 384000):
        raise ValueError("render.sample_rate must be between 8000 and 384000")
    if not (64 <= int(r.block_size) <= 65536):
        raise ValueError("render.block_size must be between 64 and 65536")
    _positive(r.loop_seconds, "render.loop_seconds")
    _range(r.loop_fade_ms, "render.loop_fade_ms", 0.0, 1000.0)
    if not (0 <= int(r.warmup_cycles) <= 64):
        raise ValueError("render.warmup_cycles must be between 0 and 64")
    _range(r.peak_db, "render.peak_db", -60.0, 0.0)
    _positive(r.resonator_length_s, "render.resonator_length_s")
    if int(r.kernel_taps) < 3:
        raise ValueError("render.kernel_taps must be >= 3")


def install_validate() -> None:
    """Attach ``validate`` to ``Preset`` (kept out of the dataclass body)."""
    Preset.validate = lambda self: _validate(self)  # type: ignore[attr-defined]


install_validate()
