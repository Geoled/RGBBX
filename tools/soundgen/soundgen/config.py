"""Preset schema and TOML loader.

A preset is the complete description of one engine *voice*: geometry, exhaust
and intake acoustics, turbo, mechanical noise and overall character. It maps
one-to-one onto the engine blueprint that the Roblox side consumes, so the same
file drives both the sound and the simulator.
"""

from __future__ import annotations

import math
import re
import tomllib
from dataclasses import asdict, dataclass, field, fields
from pathlib import Path
from typing import Any


# --------------------------------------------------------------------------- #
# dataclasses
# --------------------------------------------------------------------------- #
@dataclass
class Block:
    """Cylinder block geometry and firing configuration."""

    cylinders: int = 4
    layout: str = "inline"  # inline | v | boxer | rotary | radial | turbine
    ignition: str = "spark"  # spark | compression | turbine
    strokes: int = 4
    bore_mm: float = 87.0
    stroke_mm: float = 87.0
    compression: float = 10.5
    # Petrol octane rating. It feeds the ignition-delay correlation that drives
    # detonation in the simulator; 95 is a reasonable European pump fuel.
    octane: float = 95.0
    bank_angle_deg: float = 0.0
    rod_ratio: float = 1.6
    firing_offsets: list[float] = field(default_factory=list)
    # Volumetric-efficiency curve. 0 means "auto": peak at 55 % of the redline
    # and lose 30 % of VE by it, which is right for an ordinary engine. A
    # high-revving engine (tuned runners, big valves, race cams) holds its VE
    # far higher up, and that is the difference between a 9000 rpm V10 making
    # its power at 6500 or at 8500. Set these per preset to model one.
    ve_peak_rpm_frac: float = 0.0  # 0 = auto (0.55)
    ve_droop: float = 0.0  # 0 = auto (0.30); fraction of VE lost at the redline
    ve_peak_value: float = 0.0  # 0 = auto; >1.0 models ram-effect breathing


@dataclass
class Exhaust:
    """Exhaust acoustics: pipe length (comb), body resonances, muffling."""

    pipe_length_m: float = 1.10
    pipe_temp_c: float = 600.0
    comb_gain: float = 0.55
    comb_repeats: int = 5
    comb_invert: bool = True  # open-end reflection inverts -> quarter-wave pipe
    muffler_cutoff_hz: float = 2600.0
    bank_asymmetry: float = 0.13  # bank 1 pipe length multiplier offset
    # Primary runners: one per cylinder, between the valve and the collector.
    # 0.0 means "derive from pipe_length_m".
    runner_length_m: float = 0.0
    runner_spread: float = 0.22  # +/- fractional length spread between cylinders
    runner_reflect: float = 0.42  # reflection magnitude at the collector
    # Broadband flow roar, scaled by mass flow (rpm x load). It enters the
    # exhaust chain, so the pipe colours it like everything else.
    flow_noise: float = 0.25
    # The blowdown burst: turbulence generated by the exhaust valve opening,
    # injected once per firing event. This is the loud part of the roar.
    flow_burst: float = 0.55
    # The part of the roar that comes off the shear layer *downstream* of the
    # tailpipe, so it is heard directly and is not muffled by the pipe.
    tail_noise: float = 0.07
    flow_band_lo_hz: float = 180.0
    flow_band_hi_hz: float = 5200.0
    # Fractional rise of the quarter-wave resonance at full load (hotter gas).
    formant_shift: float = 0.16
    modes: list[list[float]] = field(
        default_factory=lambda: [
            [95.0, 2.2, 1.00],
            [190.0, 3.0, 0.85],
            [410.0, 3.5, 0.65],
            [780.0, 4.0, 0.45],
            [1450.0, 4.0, 0.28],
            [2600.0, 3.0, 0.16],
        ]
    )


@dataclass
class Intake:
    """Intake acoustics: induction roar and intake valve noise."""

    noise_gain: float = 0.30
    pulse_gain: float = 0.45
    runner_length_m: float = 0.35
    runner_spread: float = 0.18
    runner_reflect: float = 0.35
    runner_sound_speed: float = 361.0  # cold charge, ~ 60 C
    modes: list[list[float]] = field(
        default_factory=lambda: [
            [140.0, 2.5, 1.00],
            [350.0, 3.0, 0.70],
            [900.0, 3.0, 0.45],
            [2200.0, 2.5, 0.25],
        ]
    )
    band_lo_hz: float = 250.0
    band_hi_hz: float = 6500.0
    # Slope of the broadband induction noise. Air being pulled past a throttle
    # plate and through a port is turbulent, not white: its spectrum falls with
    # frequency. At 0 dB/oct the noise is a flat shelf from ``band_lo_hz`` to
    # ``band_hi_hz``, which reads as a tape hiss laid over the engine; a falling
    # slope reads as induction roar instead. The noise also inherits the
    # intake's own resonances (``modes``), the same way the pulses do, and those
    # already add to the fall -- so this is a trim, not the whole shape.
    noise_tilt_hz: float = 400.0
    noise_tilt_db_oct: float = -2.0


@dataclass
class Turbo:
    """Turbocharger / supercharger sonic character."""

    enabled: bool = False
    kind: str = "turbo"  # turbo | supercharger
    max_boost_bar: float = 1.0
    spool_rpm: float = 2400.0
    spool_span_rpm: float = 3200.0
    whistle_hz: float = 2400.0
    whistle_span_hz: float = 3600.0
    whistle_gain: float = 0.16
    # Fraction of the whistle that is present *before* the turbo spools. Zero
    # for a piston engine (a sleeping turbo is silent), high for a gas turbine
    # (its whine is shaft speed, and it is already loud at idle).
    idle_whistle: float = 0.0
    whoosh_gain: float = 0.12
    # Intercooler effectiveness, 0..1. Physics-only (the sound does not care
    # how cold the charge is), but it is a strong lever on knock: a hot charge
    # with low-octane fuel is what puts the end gas inside the autoignition
    # window. 0.70 is a decent road-car intercooler.
    charge_cooling: float = 0.70
    flutter: bool = False
    blow_off: bool = True


@dataclass
class Turbine:
    """Air-standard Brayton-cycle parameters for a gas turbine.

    These are physics-only: the sound still comes from ``[turbo]`` and the
    continuous-combustion voice.  Keeping the cycle numbers separate makes it
    possible to use the same turbine sound on a small APU and a large turboshaft
    without hand-tuning a fake torque constant.

    The reference machine is a single-shaft turboshaft: ambient air is compressed
    once, burned at ``max_turbine_inlet_c``, then expanded back through the same
    shaft.  A recuperator, variable stators and bleed air are not modelled, but
    the dominant effects -- pressure ratio, firing temperature, component
    efficiency and mass flow -- all move in the right direction.
    """

    pressure_ratio: float = 12.0
    idle_turbine_inlet_c: float = 650.0
    max_turbine_inlet_c: float = 1200.0
    compressor_efficiency: float = 0.80
    turbine_efficiency: float = 0.88
    combustor_efficiency: float = 0.98
    mechanical_efficiency: float = 0.97
    mass_flow_kg_s: float = 15.0
    # Pressure retained between compressor outlet and turbine inlet.  Combustor
    # and duct losses are small, but not zero.
    pressure_loss: float = 0.95
    # First-order shaft response.  A real single-shaft turbine accelerates in a
    # few seconds; these constants also define how quickly it returns to idle.
    spool_tau_s: float = 1.2
    wind_down_tau_s: float = 2.0


@dataclass
class Mechanical:
    """Valvetrain, rotating-assembly and accessory noise."""

    valvetrain_gain: float = 0.079
    valvetrain_bright_hz: float = 3800.0
    # Valves per cylinder. Every valve seats and lifts once per cycle, and both
    # are audible; this sets how many clicks land per cylinder per cycle (a
    # 4-valve head ticks four times, a 2-valve head twice).
    valves_per_cyl: int = 4
    # A valve closing under spring pressure is louder than the one being pushed
    # open, so the lift event is scaled by this.
    valve_open_gain: float = 0.6
    injector_gain: float = 0.025
    # Mechanical events are not perfectly repeatable: bearing clearances, chain
    # slack and cam drift scatter them by a fraction of a millisecond. A fixed
    # per-cylinder scatter decorrelates the clicks from each other *and* from
    # the exhaust pulse train (which is otherwise phase-locked to the firing
    # grid and can partially cancel them).
    mech_scatter_ms: float = 0.35
    accessory_gain: float = 0.06
    # Alternator / power-steering whine at idle. It scales with rpm, so a high
    # base frequency turns into a dog-whistle at the redline.
    accessory_hz: float = 300.0
    hiss_gain: float = 0.020  # broadband mechanical noise floor, rpm scaled
    hiss_lo_hz: float = 220.0  # ... band-limited: white noise is not a sound
    hiss_hi_hz: float = 3000.0  # ... any real engine makes
    hiss_tilt_db: float = -9.0

    # --- rotating and reciprocating assembly ------------------------------ #
    # The bottom end is what separates a recording of an engine from a pulse
    # train. Every firing load lands in the main bearings and the rod big end
    # (``crank_gain``), and every piston rocks over at TDC and slaps the bore
    # (``slap_gain``). Both are low, short thumps: they add weight, not hiss.
    crank_gain: float = 0.10
    crank_hz: float = 105.0  # scaled by engine size
    slap_gain: float = 0.08
    slap_hz: float = 210.0  # scaled by engine size
    # Timing chain / cam drive: a quiet tone at cam speed with one harmonic.
    chain_gain: float = 0.035
    chain_hz: float = 340.0  # at idle, scales with rpm
    # Continuous oil / bearing / ring shear: low band-limited noise.
    friction_gain: float = 0.022
    friction_lo_hz: float = 55.0
    friction_hi_hz: float = 380.0


@dataclass
class Space:
    """Where the engine is standing: an outdoor convolution reverb.

    Outdoors is mostly early reflections off the ground and nearby hard
    surfaces, plus a short dark tail -- not a hall. ``mix`` is the wet
    fraction; the stage is equal-power, so 0.16 keeps the dry note dominant
    while putting the engine in a real place.
    """

    enabled: bool = True
    mix: float = 0.16
    predelay_ms: float = 16.0
    decay_s: float = 0.38  # time to -60 dB
    damping_hz: float = 3800.0  # air/ground absorption of the tail
    early_gain: float = 0.55
    tail_gain: float = 0.72
    seed: int = 1



@dataclass
class Character:
    """Overall voicing: brightness, aggression, idle lumpiness, irregularity."""

    # "Brightness" is a bell around the rasp band, not a shelf: a shelf keeps
    # climbing all the way to Nyquist and lifts the hiss as much as the body.
    brightness_db: float = 0.0
    presence_hz: float = 1300.0
    presence_q: float = 0.8
    # End-of-chain air absorption. Real engine noise is never flat up to
    # Nyquist; without this the top octave is heard as hiss.
    air_cutoff_hz: float = 6000.0
    air_order: int = 3
    aggression: float = 1.0  # saturation drive (1.0 == clean)
    lumpiness: float = 0.0  # 0..1, idle lope from a hot cam
    irregularity: float = 0.04  # per-cylinder amplitude scatter
    idle_floor: float = 0.22  # combustion level at zero load
    combustion_gain: float = 1.0
    ccv: float = 0.10  # cycle-to-cycle combustion variation (line broadening)
    load_sharpening: float = 0.55  # how much the pulse sharpens at full load
    transient_bark: float = 0.6  # tip-in enrichment bark
    # The rpm at which the combustion pulse is at its reference duration; above it
    # the pulse shortens (a blowdown lasts a fixed crank angle, not a fixed
    # time). Below it the pulse is unchanged, so idle voicing is unaffected.
    pulse_ref_rpm: float = 3600.0
    pulse_min_scale: float = 0.40  # shortest pulse as a fraction of the reference


@dataclass
class Engine:
    """Operating points."""

    idle_rpm: float = 850.0
    redline_rpm: float = 7000.0
    starter_rpm: float = 260.0


@dataclass
class RenderCfg:
    """Render/stream settings. Offline quality vs real-time budget."""

    sample_rate: int = 48000
    bit_depth: int = 16
    channels: int = 1
    block_size: int = 1024
    loop_seconds: float = 3.0
    # Reserved, and deliberately unused. Loops are made *exactly* periodic by
    # quantising the firing grid, the loop length, the noise buffers and the
    # oscillator frequencies (see ``layers``), so there is nothing to fade: an
    # equal-power crossfade would add up to +3 dB on correlated material and
    # modulate the pitch at the seam. The key is kept so that existing presets
    # still load -- unknown keys are a hard error.
    loop_fade_ms: float = 12.0
    warmup_cycles: int = 3
    peak_db: float = -1.0
    resonator_length_s: float = 0.12
    kernel_taps: int = 1025


@dataclass
class Preset:
    name: str = "Untitled"
    seed: int = 0
    engine: Engine = field(default_factory=Engine)
    block: Block = field(default_factory=Block)
    exhaust: Exhaust = field(default_factory=Exhaust)
    intake: Intake = field(default_factory=Intake)
    turbo: Turbo = field(default_factory=Turbo)
    turbine: Turbine = field(default_factory=Turbine)
    mechanical: Mechanical = field(default_factory=Mechanical)
    space: Space = field(default_factory=Space)
    character: Character = field(default_factory=Character)
    render: RenderCfg = field(default_factory=RenderCfg)
    notes: str = ""

    @property
    def slug(self) -> str:
        s = re.sub(r"[^a-z0-9]+", "_", self.name.strip().lower())
        return s.strip("_") or "engine"


